export const SUBCLASS_TRAITS = S.map(([sc, edition, from, name, text]) => ({ sc, class: SUBCLASS_BY_KEY[sc]?.class ?? null, edition, from, name, text }));

const plain = (s) => String(s ?? '').toLowerCase().replace(/[’']/g, "'").replace(/\(.*?\)/g, '').replace(/^channel divinity: /, '').replace(/\s+/g, ' ').trim();

/**
 * The subclass text features this sheet has: each class's typed subclass,
 * at its level and the edition (2024 subclasses all start at 3rd), leaving
 * out any with the name of a Class features row of that subclass (Frenzy,
 * Sculpt Spells...), which shows there. [{ sc, class, subclass, from, name, text }]
 */
export function subclassTraitsOf(levels, subclasses, edition = '2014') {
  const ed = edition === '2024' ? E24 : E14;
  const rowNames = new Set();
  for (const f of [...SUBCLASS_FEATURES, ...BOOK_SUBCLASS_FEATURES]) {
    if (f.edition && f.edition !== ed) continue;
    const name = typeof f.name === 'function' ? f.name({ edition: ed, level: levels[f.class] ?? 1 }) : f.name;
    rowNames.add(`${f.sc}:${plain(name)}`);
  }
  const out = [];
  for (const t of SUBCLASS_TRAITS) {
    const sub = SUBCLASS_BY_KEY[t.sc];
    const level = levels[t.class];
    if (!sub || !level || (t.edition && t.edition !== ed)) continue;
    if (!sub.match.test(subclasses[t.class] ?? '')) continue;
    if (level < (ed === E24 ? Math.max(3, t.from) : t.from)) continue;
    if (rowNames.has(`${t.sc}:${plain(t.name)}`)) continue;
    out.push({ ...t, subclass: sub.name });
  }
  return out;
}
